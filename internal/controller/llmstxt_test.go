package controller

import (
	"flag"
	"os"
	"regexp"
	"slices"
	"strings"
	"testing"
)

const (
	llmsTxt    = "../../llms.txt"
	surfaceBeg = "<!-- api-surface: generated by `go test ./internal/controller -run TestLLMsTxtSurface -update`; do not edit -->\n"
	surfaceEnd = "<!-- /api-surface -->\n"
)

var update = flag.Bool("update", false, "rewrite llms.txt's API surface")

var (
	routeRE    = regexp.MustCompile(`mux\.HandleFunc\("([A-Z]+ /v1/[^"]*)", (.*)`)
	actionRE   = regexp.MustCompile(`^allow\(api\.Action(\w+),`)
	tsMethodRE = regexp.MustCompile(`(?m)^  (?:async )?([a-z]\w*)\(`)
	pyMethodRE = regexp.MustCompile(`(?m)^    (?:async )?def ([a-z]\w*)\(`)
)

// TestLLMsTxtSurface keeps llms.txt's list of routes and SDK methods equal to the code: the routes registered in
// Handler, A12sClient's public methods and the Python Client's.
func TestLLMsTxtSurface(t *testing.T) {
	want := surfaceBeg + apiSurface(t) + surfaceEnd
	b, err := os.ReadFile(llmsTxt)
	if err != nil {
		t.Fatal(err)
	}
	doc := string(b)
	i, j := strings.Index(doc, surfaceBeg), strings.Index(doc, surfaceEnd)
	if i < 0 || j < i {
		t.Fatalf("llms.txt has no %q ... %q block", strings.TrimSpace(surfaceBeg), strings.TrimSpace(surfaceEnd))
	}
	got := doc[i : j+len(surfaceEnd)]
	if got == want {
		return
	}
	if *update {
		if err := os.WriteFile(llmsTxt, []byte(doc[:i]+want+doc[j+len(surfaceEnd):]), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	t.Fatalf("llms.txt's API surface is stale: a route or SDK method changed. Run go test ./internal/controller -run TestLLMsTxtSurface -update, then describe the change in llms.txt's prose too")
}

func apiSurface(t *testing.T) string {
	var b strings.Builder
	b.WriteString("Routes, with the action a narrow token needs (owner: the owner token only; prefix: a prefix token, for names inside it). A prefix token may also make every action route on names inside its prefix.\n\n```text\n")
	for _, m := range routeRE.FindAllStringSubmatch(read(t, "server.go"), -1) {
		var need string
		switch a := actionRE.FindStringSubmatch(m[2]); {
		case a != nil:
			need = strings.ToLower(a[1])
		case strings.HasPrefix(m[2], `allow("", "",`):
			need = "owner"
		case strings.HasPrefix(m[2], "allowSendOrInbox("):
			need = "send or inbox"
		case strings.HasPrefix(m[2], "allowOwnerOrPrefix("):
			need = "owner, or prefix"
		case strings.HasPrefix(m[2], "func("):
			continue // answers 410 Gone with the replacement route
		default:
			t.Fatalf("server.go: %s has a wrapper this test can't name; teach apiSurface about it", m[1])
		}
		b.WriteString(m[1] + strings.Repeat(" ", max(1, 48-len(m[1]))) + need + "\n")
	}
	b.WriteString("```\n\n")
	b.WriteString("SDK objects (Python names; TypeScript is camelCase):\n\n")
	const ts, py, pyAsync = "../../sdk/typescript/src/fleet.ts", "../../sdk/python/a12s/_fleet.py", "../../sdk/python/a12s/_afleet.py"
	for _, class := range []string{"Fleet", "AgentComputers", "AgentComputer", "Services", "Service", "Tokens", "Credentials"} {
		tsm := strings.Join(methods(t, ts, "export class "+class+" {", "\n}\n", tsMethodRE), ", ")
		pym := strings.Join(methods(t, py, "\nclass "+class+":", "\nclass ", pyMethodRE), ", ")
		pyAm := strings.Join(methods(t, pyAsync, "\nclass Async"+class+":", "\nclass ", pyMethodRE), ", ")
		b.WriteString("- " + class + ": TypeScript " + tsm + "; Python " + pym)
		if pyAm != pym {
			b.WriteString("; Python Async" + class + " " + pyAm)
		}
		b.WriteString("\n")
	}
	b.WriteString("\nDeprecated one release (name-first): TypeScript A12sClient " + strings.Join(methods(t, "../../sdk/typescript/src/client.ts", "export class A12sClient {", "\n}\n", tsMethodRE), ", ") +
		"; Python Client " + strings.Join(methods(t, "../../sdk/python/a12s/_client.py", "\nclass Client:", "\nclass ", pyMethodRE), ", ") + "\n")
	return b.String()
}

func methods(t *testing.T, path, start, end string, re *regexp.Regexp) []string {
	src := read(t, path)
	i := strings.Index(src, start)
	if i < 0 {
		t.Fatalf("%s: no %q", path, start)
	}
	body := src[i+len(start):]
	if j := strings.Index(body, end); j >= 0 {
		body = body[:j]
	}
	var out []string
	for _, m := range re.FindAllStringSubmatch(body, -1) {
		// Overloads repeat a name; sharedEvents and reply are the TypeScript client's internal hooks for Fleet.
		if m[1] != "constructor" && m[1] != "sharedEvents" && m[1] != "reply" && !slices.Contains(out, m[1]) {
			out = append(out, m[1])
		}
	}
	return out
}

func read(t *testing.T, path string) string {
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}
