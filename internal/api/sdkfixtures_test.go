var update = flag.Bool("update", false, "rewrite the SDKs' API fixtures")

const (
	sdkFixtures  = "../../sdk/typescript/test/api-fixtures.gen.ts"
	jsonFixtures = "../../sdk/fixtures/api.json"
)

// TestSDKFixtures keeps the SDKs' hand-written types honest. It renders every API type, once with all fields set and
// once with only the fields Go always sends. For TypeScript they are object literals typed with the matching type, so
// tsc refuses any field the SDK lacks (excess property check), any field it requires that Go may omit, and any value
// of the wrong type. The same values go to sdk/fixtures/api.json, which the Python SDK's tests parse strictly.
func TestSDKFixtures(t *testing.T) {
	fixtures := []struct {
		name, ts string
		v        any
	}{
		{"statusResponse", "StatusResponse", StatusResponse{}},
		{"putFleetResponse", "PutFleetResponse", PutFleetResponse{}},
		{"fleetResponse", "FleetResponse", FleetResponse{}},
		{"agentComputersResponse", "AgentComputersResponse", AgentComputersResponse{}},
		{"credentialsResponse", "CredentialsResponse", CredentialsResponse{}},
		{"turnsResponse", "TurnsResponse", TurnsResponse{}},
		{"egressDeniedData", "EgressDeniedData", EgressDeniedData{}},
		{"fleetChangedData", "FleetChangedData", FleetChangedData{}},
		{"phaseData", "PhaseData", PhaseData{}},
		{"servicePhaseData", "ServicePhaseData", ServicePhaseData{}},
		{"enqueueRequest", "EnqueueRequest", EnqueueRequest{}},
		{"enqueueResponse", "EnqueueResponse", EnqueueResponse{}},
		{"message", "Message", Message{}},
		{"inboxListResponse", "InboxListResponse", InboxListResponse{}},
		{"servicesResponse", "{ services: T.ServiceStatus[] }", ServicesResponse{}},
		{"tokenRequest", "TokenRequest", TokenRequest{}},
		{"token", "Token", Token{}},
		{"event", "EventEnvelope", Event{}},
		{"turnStartedData", "TurnStartedData", TurnStartedData{}},
		{"turnFinishedData", "TurnFinishedData", TurnFinishedData{}},
		{"textDeltaData", "TextDeltaEvent[\"data\"]", TextDeltaData{}},
		{"diagnosticData", "DiagnosticData", DiagnosticData{}},
		{"resumeFailedData", "ResumeFailedData", ResumeFailedData{}},
		{"error", "ApiErrorBody", Error{}},
	}
	var b bytes.Buffer
	shared := map[string]json.RawMessage{}
	b.WriteString("// Code generated by `go test ./internal/api -run TestSDKFixtures -update`. DO NOT EDIT.\n\n")
	b.WriteString("import type * as T from \"../src/types.js\";\n")
	for _, f := range fixtures {
		ts := f.ts
		if !strings.HasPrefix(ts, "{") {
			ts = "T." + ts
		}
		for _, minimal := range []bool{false, true} {
			v := reflect.New(reflect.TypeOf(f.v)).Elem()
			fillFixture(v, "", minimal, 0)
			js, err := json.MarshalIndent(v.Interface(), "", "  ")
			if err != nil {
				t.Fatal(err)
			}
			name := f.name
			if minimal {
				name += "Minimal"
			}
			fmt.Fprintf(&b, "\nexport const %s: %s = %s;\n", name, ts, js)
			shared[name] = js
		}
	}
	js, err := json.MarshalIndent(shared, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	js = append(js, '\n')
	for _, f := range []struct {
		path string
		data []byte
	}{{sdkFixtures, b.Bytes()}, {jsonFixtures, js}} {
		if *update {
			if err := os.WriteFile(f.path, f.data, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		have, err := os.ReadFile(f.path)
		if err != nil || !bytes.Equal(have, f.data) {
			t.Fatalf("%s is stale: the API's JSON changed. Run go test ./internal/api -run TestSDKFixtures -update, then update sdk/typescript/src/types.ts until `npm run lint` passes there and sdk/python until its tests pass", f.path)
		}
	}
}

// fixtureStrings gives string fields a value the SDK's literal unions accept, by Go type or JSON name.
var fixtureStrings = map[string]string{
	"api.Phase":     string(PhaseReady),
	"api.EventType": string(EventTextDelta),
	"api.DriveKind": string(DriveWork),
	"state":         MsgPending,
	"status":        TurnCompleted,
	"actions":       ActionSend,
}

func fillFixture(v reflect.Value, name string, minimal bool, depth int) {
	if depth > 8 {
		return
	}
	switch v.Interface().(type) {
	case time.Time:
		v.Set(reflect.ValueOf(time.Date(2026, 10, 12, 12, 0, 0, 0, time.UTC)))
		return
	case json.RawMessage:
		v.Set(reflect.ValueOf(json.RawMessage(`{}`)))
		return
	}
	switch v.Kind() {
	case reflect.Struct:
		for i := range v.NumField() {
			sf := v.Type().Field(i)
			if !sf.IsExported() {
				continue
			}
			tag := sf.Tag.Get("json")
			if tag == "-" {
				continue
			}
			jsonName, opts, _ := strings.Cut(tag, ",")
			if minimal && (strings.Contains(opts, "omitempty") || strings.Contains(opts, "omitzero")) {
				continue
			}
			if sf.Anonymous {
				jsonName = name
			}
			fillFixture(v.Field(i), jsonName, minimal, depth+1)
		}
	case reflect.Pointer:
		if minimal {
			return // a field Go always sends may still be null
		}
		v.Set(reflect.New(v.Type().Elem()))
		fillFixture(v.Elem(), name, minimal, depth+1)
	case reflect.Slice:
		if v.Type().Elem().Kind() == reflect.Uint8 {
			v.SetBytes([]byte("x"))
			return
		}
		v.Set(reflect.MakeSlice(v.Type(), 1, 1))
		fillFixture(v.Index(0), name, minimal, depth+1)
	case reflect.Map:
		m := reflect.MakeMap(v.Type())
		val := reflect.New(v.Type().Elem()).Elem()
		fillFixture(val, name, minimal, depth+1)
		m.SetMapIndex(reflect.ValueOf("k").Convert(v.Type().Key()), val)
		v.Set(m)
	case reflect.String:
		s, ok := fixtureStrings[v.Type().String()]
		if !ok {
			s, ok = fixtureStrings[name]
		}
		if !ok {
			s = name
		}
		v.SetString(s)
	case reflect.Bool:
		v.SetBool(true)
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		v.SetInt(1)
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		v.SetUint(1)
	case reflect.Float32, reflect.Float64:
		v.SetFloat(1.5)
	}
}
